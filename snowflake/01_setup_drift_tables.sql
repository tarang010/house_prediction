USE DATABASE HOUSE_PRICE_MLOPS;
USE SCHEMA ML;

-- Store actual ground-truth prices separately from model predictions.
ALTER TABLE HOUSE_PRICE_MLOPS.ML.PRODUCTION_DATA
    ADD COLUMN IF NOT EXISTS ACTUAL_PRICE NUMBER(12,2);

-- Track every completed drift check.
CREATE TABLE IF NOT EXISTS HOUSE_PRICE_MLOPS.ML.DRIFT_RESULTS (
    CHECK_ID VARCHAR DEFAULT UUID_STRING(),
    CHECK_TIME TIMESTAMP_NTZ,
    REFERENCE_ROWS NUMBER,
    PRODUCTION_ROWS NUMBER,
    DRIFTED_FEATURES VARCHAR,
    DRIFT_DETECTED BOOLEAN,
    ALERT_STATUS VARCHAR
);

-- Stage production observations. A candidate is eligible for supervised
-- retraining only after ACTUAL_PRICE is supplied.
CREATE TABLE IF NOT EXISTS HOUSE_PRICE_MLOPS.ML.RETRAINING_CANDIDATES (
    SOURCE_PREDICTION_ID VARCHAR,
    SQFT NUMBER,
    BEDROOMS NUMBER,
    BATHROOMS FLOAT,
    LOCATION VARCHAR,
    YEAR_BUILT NUMBER,
    CONDITION VARCHAR,
    PREDICTED_PRICE NUMBER(12,2),
    ACTUAL_PRICE NUMBER(12,2),
    CAPTURED_AT TIMESTAMP_NTZ,
    CANDIDATE_STATUS VARCHAR DEFAULT 'AWAITING_LABEL'
);

-- Add a lineage key to RAW_DATA to prevent re-ingesting the same production row.
ALTER TABLE HOUSE_PRICE_MLOPS.ML.RAW_DATA
    ADD COLUMN IF NOT EXISTS SOURCE_PREDICTION_ID VARCHAR;
