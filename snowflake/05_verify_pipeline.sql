-- 1. Recent drift checks
SELECT *
FROM HOUSE_PRICE_MLOPS.ML.DRIFT_RESULTS
ORDER BY CHECK_TIME DESC
LIMIT 20;

-- 2. Candidate counts by state
SELECT CANDIDATE_STATUS, COUNT(*) AS ROW_COUNT
FROM HOUSE_PRICE_MLOPS.ML.RETRAINING_CANDIDATES
GROUP BY CANDIDATE_STATUS
ORDER BY CANDIDATE_STATUS;

-- 3. Latest production records
SELECT
    PREDICTION_ID,
    SQFT,
    LOCATION,
    PREDICTED_PRICE,
    ACTUAL_PRICE,
    PREDICTION_TIME,
    MODEL_VERSION
FROM HOUSE_PRICE_MLOPS.ML.PRODUCTION_DATA
ORDER BY PREDICTION_TIME DESC
LIMIT 20;

-- 4. Recent scheduled task runs
SELECT *
FROM TABLE(
    HOUSE_PRICE_MLOPS.INFORMATION_SCHEMA.TASK_HISTORY(
        SCHEDULED_TIME_RANGE_START =>
            DATEADD('day', -1, CURRENT_TIMESTAMP()),
        RESULT_LIMIT => 20
    )
)
WHERE NAME = 'HOUSE_PRICE_DRIFT_HOURLY_TASK'
ORDER BY SCHEDULED_TIME DESC;

-- 5. Check whether labels are available for retraining
SELECT
    COUNT_IF(CANDIDATE_STATUS = 'AWAITING_LABEL') AS AWAITING_LABEL,
    COUNT_IF(CANDIDATE_STATUS = 'READY') AS READY_TO_INGEST,
    COUNT_IF(CANDIDATE_STATUS = 'INGESTED') AS INGESTED
FROM HOUSE_PRICE_MLOPS.ML.RETRAINING_CANDIDATES;