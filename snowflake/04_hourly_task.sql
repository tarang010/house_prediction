USE DATABASE HOUSE_PRICE_MLOPS;
USE SCHEMA ML;

-- Create/recreate the task in suspended state.
CREATE OR REPLACE TASK HOUSE_PRICE_MLOPS.ML.HOUSE_PRICE_DRIFT_HOURLY_TASK
    WAREHOUSE = ML_WH
    SCHEDULE = '60 MINUTES'
AS
BEGIN
    CALL HOUSE_PRICE_MLOPS.ML.CHECK_HOUSE_PRICE_DRIFT();
    CALL HOUSE_PRICE_MLOPS.ML.INGEST_LABELLED_HOUSE_PRICES();
END;

-- Enable the hourly schedule.
ALTER TASK HOUSE_PRICE_MLOPS.ML.HOUSE_PRICE_DRIFT_HOURLY_TASK RESUME;

-- Check state.
SHOW TASKS LIKE 'HOUSE_PRICE_DRIFT_HOURLY_TASK'
    IN SCHEMA HOUSE_PRICE_MLOPS.ML;