USE DATABASE HOUSE_PRICE_MLOPS;
USE SCHEMA ML;

CREATE OR REPLACE PROCEDURE HOUSE_PRICE_MLOPS.ML.INGEST_LABELLED_HOUSE_PRICES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    v_ingested NUMBER DEFAULT 0;
BEGIN
    -- Never use PREDICTED_PRICE as PRICE. Only ACTUAL_PRICE is the target.
    INSERT INTO HOUSE_PRICE_MLOPS.ML.RAW_DATA (
        PRICE,
        SQFT,
        BEDROOMS,
        BATHROOMS,
        LOCATION,
        YEAR_BUILT,
        CONDITION,
        SOURCE_PREDICTION_ID
    )
    SELECT
        c.ACTUAL_PRICE,
        c.SQFT,
        c.BEDROOMS,
        c.BATHROOMS,
        c.LOCATION,
        c.YEAR_BUILT,
        c.CONDITION,
        c.SOURCE_PREDICTION_ID
    FROM HOUSE_PRICE_MLOPS.ML.RETRAINING_CANDIDATES c
    WHERE c.CANDIDATE_STATUS = 'READY'
      AND c.ACTUAL_PRICE IS NOT NULL
      AND c.SOURCE_PREDICTION_ID IS NOT NULL
      AND NOT EXISTS (
          SELECT 1
          FROM HOUSE_PRICE_MLOPS.ML.RAW_DATA r
          WHERE r.SOURCE_PREDICTION_ID = c.SOURCE_PREDICTION_ID
      );

    v_ingested := SQLROWCOUNT;

    -- Mark candidates whose source ID is now present in RAW_DATA.
    UPDATE HOUSE_PRICE_MLOPS.ML.RETRAINING_CANDIDATES c
       SET CANDIDATE_STATUS = 'INGESTED'
     WHERE c.CANDIDATE_STATUS = 'READY'
       AND c.ACTUAL_PRICE IS NOT NULL
       AND EXISTS (
           SELECT 1
           FROM HOUSE_PRICE_MLOPS.ML.RAW_DATA r
           WHERE r.SOURCE_PREDICTION_ID = c.SOURCE_PREDICTION_ID
       );

    RETURN 'Labelled records ingested into RAW_DATA: ' || v_ingested;
END;
$$;